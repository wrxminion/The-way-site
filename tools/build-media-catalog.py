#!/usr/bin/env python3
"""Builds site/members/media-catalog.js for the Media page picker, and can print a seed SQL file.

Run from the repo root:  python tools/build-media-catalog.py [seed.sql]
Reads only page titles and the case list from files in site/. Paths are paths on this site (no outside links).
The titles and paths are already public. The catalog file is loaded only by the members Media page, so no public page changes.
Counts (articles per topic) are counted here from the real case list, never typed.
"""
import html, json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SITE = os.path.join(ROOT, 'site')
SAFE_PATH = re.compile(r'^/[A-Za-z0-9_./~-]*$')


def read(p):
    with open(os.path.join(SITE, p), encoding='utf-8') as f:
        return f.read()


def title_of(text):
    m = re.search(r'<title>(.*?)</title>', text, re.S)
    if not m:
        return None
    t = html.unescape(re.sub(r'\s+', ' ', m.group(1))).strip()
    t = re.sub('\\s*[-' + chr(0x2014) + chr(0x2013) + '|]\\s*The Way\\s*$', '', t).strip()
    t = t.replace(chr(0x2014), '-').replace(chr(0x2013), '-')   # no long dashes in anything we assemble
    return t if t and not re.search(r'[<>]', t) and len(t) <= 200 else None


pages, skipped = [], []


def add(path, kind, title):
    if not title or not SAFE_PATH.match(path) or len(path) > 200:
        skipped.append(path)
        return
    pages.append({'path': path, 'title': title, 'kind': kind})


def guide_dirs():
    return [d for d in sorted(os.listdir(SITE)) if d == 'guide' or re.fullmatch(r'guide-[a-z]{2}', d)]


# state guides: /guide/ (Colorado) and /guide-xx/
for d in guide_dirs():
    idx = os.path.join(d, 'index.html')
    if os.path.exists(os.path.join(SITE, idx)):
        add('/' + d + '/', 'guide', title_of(read(idx)))

# judges pages
for d in guide_dirs():
    races = os.path.join(SITE, d, 'races')
    if os.path.isdir(races):
        for f in sorted(os.listdir(races)):
            if re.fullmatch(r'judges(-rtd)?\.html', f):
                add('/%s/races/%s' % (d, f), 'judges', title_of(read(os.path.join(d, 'races', f))))

# civics and history cases: the real list on the cases hub, with topic counts
hub = read('cases/index.html')
cards = re.findall(r'<a class="hub-card" href="([^"]+\.html)"[^>]*>.*?<span class="depth">([^<]*)</span>', hub, re.S)
topic_counts = {}
for href, depth in cards:
    p = os.path.join('cases', href)
    if not os.path.exists(os.path.join(SITE, p)):
        continue
    parts = [s.strip() for s in depth.split('·')]
    topic = parts[1] if len(parts) > 1 else ''
    before = len(pages)
    add('/cases/' + href, 'case', title_of(read(p)))
    if topic and len(pages) > before:
        topic_counts[topic] = topic_counts.get(topic, 0) + 1

# a few real hub pages and the research packages
for path, rel in [('/vote/', 'vote/index.html'), ('/cases/', 'cases/index.html'),
                  ('/how-government-works.html', 'how-government-works.html'),
                  ('/research/', 'research/index.html'), ('/news/', 'news/index.html'), ('/map/', 'map/index.html')]:
    if os.path.exists(os.path.join(SITE, rel)):
        add(path, 'site', title_of(read(rel)))
pk = os.path.join(SITE, 'research', 'packages')
if os.path.isdir(pk):
    for name in sorted(os.listdir(pk)):
        rel = os.path.join('research', 'packages', name, 'index.html')
        if os.path.exists(os.path.join(SITE, rel)):
            add('/research/packages/%s/' % name, 'research', title_of(read(rel)))

seen, uniq = set(), []
for p in pages:
    if p['path'] not in seen:
        seen.add(p['path'])
        uniq.append(p)
pages = uniq

cases_hub = next((p for p in pages if p['path'] == '/cases/'), None)
topics = []
if cases_hub:
    for label, n in sorted(topic_counts.items(), key=lambda kv: (-kv[1], kv[0])):
        if n > 0:
            topics.append({'label': label, 'count': n, 'path': '/cases/', 'title': cases_hub['title']})

out = os.path.join(SITE, 'members', 'media-catalog.js')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/build-media-catalog.py. Do not edit by hand. Used only by the members Media page picker.\n')
    f.write('// Paths are on this site only. Titles and paths are already public, so no public page changes.\n')
    f.write('window.TheWayCatalog = ' + json.dumps({'origin': 'https://michiinstitute.com', 'pages': pages, 'topics': topics},
                                                    ensure_ascii=True, indent=1) + ';\n')
print('pages', len(pages), 'topics', len(topics), 'skipped', len(skipped), file=sys.stderr)

if len(sys.argv) > 1:
    def q(s):
        return "'" + s.replace("'", "''") + "'"

    judges = [p for p in pages if p['kind'] == 'judges']
    by = lambda path: next((p for p in pages if p['path'] == path), None)
    guide_co, vote, how = by('/guide/'), by('/vote/'), by('/how-government-works.html')
    pkg = next((p for p in pages if p['kind'] == 'research'), None)
    top = topics[0] if topics else None
    posts = [('Come read about your judges before you vote!', p) for p in judges]
    if guide_co:
        posts.append(('Your state guide lists what is on your ballot, in plain words. Come take a look before you vote.', guide_co))
    if vote:
        posts.append(('Make a plan before you vote. Come see how it works.', vote))
    if top and top['count'] >= 2:
        posts.append(('We have %d articles about %s, come see our research on it.' % (top['count'], top['label'].lower()),
                      {'path': top['path'], 'title': top['title']}))
    ideas = []
    if judges:
        ideas.append(('Point people to their state judges page a few days before the election, in a post that links the page.',
                      'Judges are the part of the ballot people know least about.', judges[-1]))
    if top:
        ideas.append(('Share the civics and history cases that match the news of the week, with a link to the case.',
                      'Real cases give a debate something to stand on.', {'path': top['path'], 'title': top['title']}))
    if how:
        ideas.append(('When an argument is about who does what in government, link our how-government-works page.',
                      'It answers a common question with sources.', how))
    if pkg:
        ideas.append(('When someone asks for sources, share the research package page.',
                      'A page people can point to as proof.', pkg))
    canned = [
        ('Who funds this? The Way takes no donations and runs no ads. It is a personal website, so no outside money decides what it shows. The sources for every claim are on the page.', 'Answers a common question plainly.'),
        ('Are you left or right? Neither. The Way is not a party and does not endorse anyone. We show both sides of a claim with their sources, and you decide.', 'Keeps the answer neutral and short.'),
        ('How do you check claims? We look for two sources and one primary source, like the original document. We show both sides. If something is not proven, we say alleged.', 'Explains the method in three steps.'),
        ('Where is the source? Sources are on the page. Each claim lists them, so you can open them and read for yourself.', 'Points people to the proof.'),
        ('Can I trust AI? Do not trust any speaker just because of who or what it is. Check the evidence. We label pages made with AI, and the sources are always shown so you can check them.', 'Honest answer that moves to evidence.'),
        ('Why no donations? Money can push what gets shown. The Way takes no donations, so no money influences what we show you.', 'Explains the no donations rule.'),
    ]
    debate = [
        # A: bad faith or trolls. Drop the sources once, then disengage.
        ('Here is some good sauce, may you find peace on your path.', 'Use for bad faith or trolls. Drop the link once, then go quiet. Do not reply again.', by('/how-government-works.html')),
        ('The sources are below if you ever want them. I will leave it here. You take care now.', 'Use for someone who only wants a fight. Drop the link once, then go quiet. Do not reply again.', by('/cases/')),
        ("Ohh that's cute, here is some sauce.", 'Light and teasing. Can read as a dig, so use only when the tone is already playful.', by('/research/')),
        ("Ohhh my sweet summer child, here is some sauce.", 'Playful and teasing. Can read as condescending, so use only when the tone is already light.', by('/vote/')),
        # B: people who engage with the sources. Offer more research.
        ('Good point. Here is a second source and the primary document that bears on it. If it disproves our claim, we will correct it.', 'Use when someone reads the sources and answers calmly. Offer more research.'),
        ('Thank you kindly for reading it. Which part of the source do you read differently? Show me the line and I will look at it with you.', 'Use when someone engages with a source but disagrees on one part. Ask for the exact line.'),
        ('Well now, that is a fair challenge. Here is more research that tests the claim from the other side, with its sources.', 'Use when someone brings a real counter point. Reply with more research that supports or disproves the claim.'),
        # C: corrections. Plain and direct, no apology.
        ('Correction: we had this wrong. Here is the updated claim and the source. What changed: [fill in what changed].', 'Use when we find our claim was wrong. Say it plainly, no apology, and show what changed.'),
        ('Correction: you are right on this point. The claim now reads: [fill in the new claim]. Source: [fill in the source].', 'Use when a reader shows us a mistake. Fix it in public and name the new source.'),
        ('Update: this page was changed. Old claim: [fill in the old claim]. New claim: [fill in the new claim]. Why: [fill in the reason and source].', 'Use after a page is updated, so old shares stay correct.'),
    ]
    L = []
    L.append('-- RUN THIS in the Supabase SQL editor after 0094 (one paste). Draft Facebook posts and ideas that use real links, plus starter canned responses and debate replies.')
    L.append('-- Plain inserts with ON CONFLICT DO NOTHING, so running it twice adds nothing twice. Every row is a DRAFT for an admin to approve.')
    L.append('-- Links are paths on michiinstitute.com. Titles were taken from the real pages by tools/build-media-catalog.py.')
    L.append('-- The "N articles" number was counted from the real cases list when this file was made.')
    L.append('')
    L.append('insert into public.social_posts (platform, body, link_path, link_title, status, source) values')
    L.append(',\n'.join('  (%s, %s, %s, %s, %s, %s)' % (q('facebook'), q(b), q(p['path']), q(p['title']), q('draft'), q('human')) for b, p in posts))
    L.append("on conflict (platform, body, (coalesce(link_path, ''))) do nothing;")
    L.append('')
    rows = ['  (%s, %s, %s, %s, %s, %s, %s, %s)' % (q(b), q(r), q('idea'), q('idea'), q('draft'), q('human'), q(p['path']), q(p['title'])) for b, r, p in ideas]
    rows += ['  (%s, %s, %s, %s, %s, %s, null, null)' % (q(b), q(r), q('copy'), q('canned_response'), q('draft'), q('human')) for b, r in canned]
    def dbrow(e):
        b, r = e[0], e[1]
        if len(e) > 2 and e[2]:
            return '  (%s, %s, %s, %s, %s, %s, %s, %s)' % (q(b), q(r), q('copy'), q('debate_reply'), q('draft'), q('human'), q(e[2]['path']), q(e[2]['title']))
        return '  (%s, %s, %s, %s, %s, %s, null, null)' % (q(b), q(r), q('copy'), q('debate_reply'), q('draft'), q('human'))
    rows += [dbrow(e) for e in debate]
    L.append('insert into public.marketing_ideas (body, reason, kind, category, status, source, link_path, link_title) values')
    L.append(',\n'.join(rows))
    L.append("on conflict (kind, body, (coalesce(link_path, ''))) do nothing;")
    L.append('')
    L.append('select (select count(*) from public.social_posts where link_path is not null) as posts_with_links,')
    L.append('       (select count(*) from public.marketing_ideas where link_path is not null) as ideas_with_links;')
    with open(sys.argv[1], 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L) + '\n')
    print('seed posts', len(posts), 'ideas', len(ideas), file=sys.stderr)
